CREATE TABLE IF NOT EXISTS shops (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL,
 plan VARCHAR(20) NOT NULL DEFAULT 'Free', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS users (
 id INT PRIMARY KEY AUTO_INCREMENT, shop_id INT NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(512) NOT NULL, failed_attempts INT NOT NULL DEFAULT 0, locked_until DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(shop_id) REFERENCES shops(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id INT PRIMARY KEY AUTO_INCREMENT, shop_id INT NOT NULL,
 name VARCHAR(120) NOT NULL, category VARCHAR(60) NOT NULL, unit VARCHAR(40) NOT NULL,
 price DECIMAL(10,2) NOT NULL CHECK(price>=0), quantity INT NOT NULL CHECK(quantity>=0),
 reorder_level INT NOT NULL CHECK(reorder_level>=0), daily_sales DECIMAL(10,2) NOT NULL CHECK(daily_sales>=0),
 UNIQUE KEY(shop_id,id), FOREIGN KEY(shop_id) REFERENCES shops(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS photos (
 id INT PRIMARY KEY AUTO_INCREMENT, shop_id INT NOT NULL, file_name VARCHAR(80) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY(shop_id,id), FOREIGN KEY(shop_id) REFERENCES shops(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_movements (
 id INT PRIMARY KEY AUTO_INCREMENT, shop_id INT NOT NULL, product_id INT NOT NULL,
 old_quantity INT NOT NULL, new_quantity INT NOT NULL, reason VARCHAR(240) NOT NULL, photo_id INT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(shop_id,product_id) REFERENCES products(shop_id,id),
 FOREIGN KEY(shop_id,photo_id) REFERENCES photos(shop_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
 id INT PRIMARY KEY AUTO_INCREMENT, shop_id INT NOT NULL, supplier VARCHAR(120) NOT NULL,
 channel VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'Draft',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY(shop_id,id), FOREIGN KEY(shop_id) REFERENCES shops(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_items (
 shop_id INT NOT NULL, order_id INT NOT NULL, product_id INT NOT NULL, quantity INT NOT NULL CHECK(quantity>0),
 unit_cost DECIMAL(10,2) NOT NULL, PRIMARY KEY(order_id,product_id),
 FOREIGN KEY(shop_id,order_id) REFERENCES orders(shop_id,id),
 FOREIGN KEY(shop_id,product_id) REFERENCES products(shop_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
